-- NexaPos free AI Support: deterministic FAQ bot, conversation handoff, and admin inbox state.
-- No external AI provider or paid API is used.

ALTER TABLE public.support_messages
  DROP CONSTRAINT IF EXISTS support_messages_sender_role_check;
ALTER TABLE public.support_messages
  ADD CONSTRAINT support_messages_sender_role_check
  CHECK (sender_role = ANY (ARRAY['customer'::text, 'support'::text, 'bot'::text]));

CREATE TABLE IF NOT EXISTS public.support_conversations (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'ai_active'
    CHECK (status IN ('ai_active', 'waiting_admin', 'admin_active', 'resolved')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_message_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.support_conversations ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS support_conversations_read_scoped ON public.support_conversations;
CREATE POLICY support_conversations_read_scoped ON public.support_conversations
  FOR SELECT TO authenticated
  USING (
    private.is_super_admin()
    OR (
      user_id = (SELECT auth.uid())
      AND (
        private.is_pin_verified()
        OR COALESCE(((SELECT auth.jwt()) ->> 'is_anonymous')::boolean, false)
      )
    )
  );

CREATE TABLE IF NOT EXISTS public.support_knowledge_base (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL,
  question text NOT NULL,
  answer text NOT NULL,
  keywords text[] NOT NULL DEFAULT '{}',
  priority integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.support_knowledge_base ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS support_knowledge_admin_read ON public.support_knowledge_base;
CREATE POLICY support_knowledge_admin_read ON public.support_knowledge_base
  FOR SELECT TO authenticated
  USING (private.is_super_admin());
DROP POLICY IF EXISTS support_knowledge_admin_write ON public.support_knowledge_base;
CREATE POLICY support_knowledge_admin_write ON public.support_knowledge_base
  FOR ALL TO authenticated
  USING (private.is_super_admin())
  WITH CHECK (private.is_super_admin());

-- Allow customers using the existing anonymous live-chat flow to read only their own messages.
DROP POLICY IF EXISTS support_messages_read_pin_verified ON public.support_messages;
CREATE POLICY support_messages_read_pin_verified ON public.support_messages
  FOR SELECT TO authenticated
  USING (
    private.is_super_admin()
    OR (
      user_id = (SELECT auth.uid())
      AND (
        private.is_pin_verified()
        OR COALESCE(((SELECT auth.jwt()) ->> 'is_anonymous')::boolean, false)
      )
    )
  );

